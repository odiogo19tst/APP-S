'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const assets=path.join(__dirname,'../app/src/main/assets');
const ux=fs.readFileSync(path.join(assets,'ux-v2.js'),'utf8');
const css=fs.readFileSync(path.join(assets,'ux-v2.css'),'utf8');
const rig=require('../app/src/main/assets/song-rig.js');
const brain=require('../app/src/main/assets/setup-brain.js');
const jsName='Grauê Palco 1.31.0';
assert(ux.includes('id="gx-stage-reapply-rig"'),'Palco needs manual recovery');
assert(ux.includes('id="gx-stage-health"'),'Visible USB/SysEx status required');
assert(ux.includes("if(!usbConnected){hw={};rigRunner?.cancel();"),'USB loss must clear stale readback');
assert(ux.includes('activeSongIndex=()=>'),'Song identity guard missing');
assert(ux.includes('matches.length===1?matches[0]:-1'),'Ambiguous duplicate song title must not choose arbitrary rig');
assert(ux.includes('i===activeSongIndex()'), 'Active song UI must compare selected index');
assert(ux.includes('const next=(at+1+songs.length)%songs.length;selectRepertoireSong(songs[next],next);sync();'),
 'Next music must follow the same safe MIDI path as repertoire selection');
assert(!ux.includes("selectedIndex=(at+1+songs.length)%songs.length;select(songs[selectedIndex]);"),
 'Do not navigate without applying next song setup');
assert(ux.includes('if(!preset||!preset.auto)'), 'Retry may not override manually configured songs');
assert(ux.includes('rigRunner?.prepare(planned,activeRigToken())'),'Active song token should survive duplicate song titles');
assert(ux.includes('rigRunner?.receive(kind,data,hw,activeRigToken())'),'Late MIDI response must never target a new song');
assert(ux.includes("!usbConnected?'Modo cifra disponível · USB desconectado"),'Offline stage should remain available');
assert(ux.includes("USB conectado · aguardando leitura SysEx"),'USB alone must not be presented as confirmed Roland connection');
assert(css.includes('.gx-stage-reapply-rig')&&css.includes('min-height:44px'),'Recover button must be touch accessible');
const setup={type:'user',number:3,auto:true,parts:[{part:0,values:{7:90}}]};
const music={title:'Maranata',keyboardSetup:setup};
assert.equal(rig.activate(music,false,()=>{throw Error('No USB MIDI should be emitted');}).status,'disconnected');
assert.equal(rig.activate({title:'Maranata'},true,()=>{throw Error('No rig configured');}).status,'not-configured');
let sends=[];const runner=brain.createRunner(edits=>sends.push(edits));
assert(runner.prepare(setup,'song:3:Maranata'));
runner.receive('performanceSelected',{index:3,user:true},null,'song:3:Maranata');
runner.receive('hardwareBusy',true,null,'song:3:Maranata');
assert.equal(runner.receive('hardware',{readAt:Date.now()+1000},null,'song:4:Maranata').status,'cancelled');
assert.equal(sends.length,0,'An old response must never affect an identically titled next song');
assert(!runner.isPending(),'Stale song token must discard pending operations');
assert(runner.prepare(setup,'song:3:Maranata'));
assert.equal(runner.receive('xpsConnection',false,null,'song:3:Maranata').status,'disconnected');
assert.equal(sends.length,0,'USB disconnection cancels staged writes');
const manually={title:'Maranata',keyboardSetup:{...setup,auto:false}};
assert.equal(rig.activate(manually,true,()=>{throw Error('Do not send manual rigs');}).status,'manual');
console.log(jsName+': next-song automatic setup, manual retry, stale MIDI protection and offline readiness PASS');
