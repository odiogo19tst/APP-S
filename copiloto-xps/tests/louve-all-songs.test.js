'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const base=path.join(__dirname,'../app');
const L=require(path.join(base,'src/main/assets/louve-import.js'));
const M=require(path.join(base,'src/main/assets/music.js'));
const pasted=fs.readFileSync(path.join(__dirname,'fixtures/louve-scale-2026-11-22.txt'),'utf8');
const scale=L.parse(pasted);
assert.equal(scale.title,'Culto Louvor e Adoração');
assert.equal(scale.dateLine,'Domingo, 22 de novembro de 2026 · 16:30');
assert.deepEqual(scale.items.map(i=>i.title),['1000 Graus (Live)','Deus do Secreto','Alfa e Ômega']);
assert.deepEqual(scale.items.map(i=>i.artist),['Renascer Praise','Ministério Sarando a Terra Ferida','Marine Friesen']);
assert.deepEqual(scale.items.map(i=>i.key),['C','F','E']);
assert.deepEqual(scale.items.map(i=>i.bpm),[153,65,146]);
assert.deepEqual(scale.items.map(i=>i.order),[1,2,3]);
assert(scale.items.every(i=>i.sourceUrl.startsWith('https://')));
assert.equal(scale.items[1].sourceUrl,'https://www.cifraclub.com.br/ministerio-sarando-terra-ferida/deus-do-secreto');
assert.equal(scale.items[2].sourceUrl,'https://www.cifraclub.com.br/marine-friesen/alfa-e-omega/principal.html');
assert.deepEqual(scale.items.map(i=>i.youtubeUrl.includes('youtu.be')), [true,true,true]);
const previous={loopId:'old-performance',title:'Música antiga',category:'Culto anterior',chords:['G'],text:'Arranjo pessoal',keyboardSetup:{type:'user',number:9}};
const songs=[previous];
let identity=0;
const normalize=s=>({loopId:'louve-'+(++identity),...s});
const first=L.ensureSongs(songs,scale,M,normalize);
assert.deepEqual(first,{added:3,reused:0,total:3});
assert.equal(songs.length,4,'All three songs must appear immediately, before any Cifra Club response');
assert.equal(songs[0],previous,'Do not replace prior repertoire');
assert.deepEqual(songs.slice(1).map(i=>i.title),scale.items.map(i=>i.title));
assert.deepEqual(songs.slice(1).map(i=>i.bpm),[153,65,146]);
assert.deepEqual(songs.slice(1).map(i=>i.root),[0,5,4]);
assert(songs.slice(1).every(i=>i.scoreNotes.includes('não é a harmonia')),'Do not misrepresent a placeholder as a downloaded score');
assert(songs.slice(1).every(i=>i.text===''),'No lyrics/chords may be fabricated');
assert.deepEqual(L.orderedIndexes(songs,scale),[1,2,3,0],'Original setlist order must be used despite unfinished score extraction');
songs[2].text='Cifra anotada pelo músico';
songs[2].chords=['F','Bb','C'];
songs[2].keyboardSetup={type:'user',number:7};
songs[2].scoreNotes='Minha anotação do ensaio';
const originalId=songs[2].loopId;
const again=L.ensureSongs(songs,scale,M,normalize);
assert.deepEqual(again,{added:0,reused:3,total:3});
assert.equal(songs.length,4,'Re-pasting cannot duplicate a setlist');
assert.equal(songs[2].loopId,originalId);
assert.equal(songs[2].keyboardSetup.number,7);
assert.equal(songs[2].text,'Cifra anotada pelo músico');
assert.deepEqual(songs[2].chords,['F','Bb','C']);
assert.equal(songs[2].scoreNotes,'Minha anotação do ensaio');
const ui=fs.readFileSync(path.join(base,'src/main/assets/ux-v2.js'),'utf8');
const panel=fs.readFileSync(path.join(base,'src/main/java/br/com/doapps/grauelive/CifraPanel.java'),'utf8');
assert(ui.includes('GraueLouve.ensureSongs(songs,set,M,normalize)'), 'The UI must seed all songs before asynchronous extraction');
assert(ui.indexOf('GraueLouve.ensureSongs(songs,set,M,normalize)')<ui.indexOf('startLouve(set.items);'),'The metadata transaction precedes network work');
assert(ui.includes("música salva; cifra pendente"),'Failed score must remain visible');
assert(ui.includes('músicas no repertório'),'Completion summary must distinguish songs from downloaded scores');
assert(panel.includes('static String canonicalPath(String url)'),'Cifra Club paths must be normalized');
assert(panel.includes('canonicalPath(expected).equals(canonicalPath(current))'),'Canonical slash and principal.html matching required');
console.log('LouveApp 2026-11-22: 3/3 songs imported locally, correct order/key/BPM/links, idempotent merge, offline fallback and canonical URL test PASS');
