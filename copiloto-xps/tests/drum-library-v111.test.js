const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const base=path.resolve(__dirname,'../app/src/main');
const catalog=fs.readFileSync(path.join(base,'assets/tones-data.js'),'utf8');
const js=fs.readFileSync(path.join(base,'assets/drumpads.js'),'utf8');
const ui=fs.readFileSync(path.join(base,'assets/ux-v2.js'),'utf8');
const native=fs.readFileSync(path.join(base,'java/br/com/doapps/grauelive/MainActivity.java'),'utf8');
const audio=fs.readFileSync(path.join(base,'java/br/com/doapps/grauelive/DrumSampleLibrary.java'),'utf8');
const css=fs.readFileSync(path.join(base,'assets/ux-v2.css'),'utf8');
const context={window:{}};vm.runInNewContext(catalog,context);
const kits=context.window.XPS_TONES.filter(t=>t.category==='DRM'&&/^Dr[0-9]{3}$/.test(t.code));
assert.equal(kits.length,28,'The current XPS-10 factory catalogue must have 19 drum kits and 9 GM2 kits');
assert.equal(kits[0].code,'Dr001');
assert.equal(kits[27].code,'Dr028');
for(const name of ['Drum Kit 1','EFX 1','Worship Drums','Worship EFX'])assert(ui.includes(name),'Library selector missing: '+name);
for(const id of ['gx-roland-kit','gx-roland-kit-send','gx-drums-library','gx-drum-audio-bank','gx-drum-sample-slots'])assert(ui.includes(id),'UI missing: '+id);
assert(js.includes("category==='DRM'"),'Must load actual drum kits, not guessed patches');
assert(js.includes("native('selectDrumKit',tone.msb,tone.lsb,tone.program,drumChannel)"),'Kit select must transmit MIDI bank/program');
assert(js.includes("native('playDrumSample',sampleBank(),index)"),'Samples must play on Android');
assert(js.includes("native('importDrumSample',sampleBank(),i)"),'Each slot must import audio');
assert(js.includes("native('listDrumSamples',sampleBank())"),'Bank must reload sample metadata');
assert(js.includes('if(isAudio())'),'Audio mode must not execute MIDI beat loop');
assert(native.includes('@JavascriptInterface public void selectDrumKit'),'Native MIDI patch select unavailable');
assert(native.includes('midi.sendProgram(channel,program-1)'),'Program Change must use two-byte MIDI command');
for(const k of ['listDrumSamples(int bank)','importDrumSample(int bank,int pad)','playDrumSample(int bank,int pad)','stopDrumSamples()'])assert(native.includes(k),'Android sample bridge missing: '+k);
assert(native.includes('if(req==7)'),'Missing system file chooser result');
assert(audio.includes('new SoundPool.Builder()')&&audio.includes('sounds.play('),'Real audio player required');
assert(audio.includes('getFilesDir()')&&audio.includes('12L*1024*1024'),'Sandboxed audio and safe file limits required');
assert(audio.includes('pos(bank,slot)')&&audio.includes('bank<2||bank>3'),'Two independent Worship banks required');
assert(css.includes('.gx-drum-library-tabs')&&css.includes('.gx-drum-sample-slots'),'Drum library responsive styles required');
console.log('Drum Studio library: 28 Roland factory kits, 4 profiles, independent sample banks, real MIDI and audio import bridge verified');
