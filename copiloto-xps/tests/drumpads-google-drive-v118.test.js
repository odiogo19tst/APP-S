const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../app/src/main');
const ui=fs.readFileSync(path.join(root,'assets/drumpads.js'),'utf8');
const java=fs.readFileSync(path.join(root,'java/br/com/doapps/grauelive/MainActivity.java'),'utf8');
const eng=fs.readFileSync(path.join(root,'java/br/com/doapps/grauelive/PadSampleEngine.java'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/ux-v2.css'),'utf8');
assert(ui.includes('id="gx-pad-export-drive"'),'Kit export button missing');
assert(ui.includes('id="gx-pad-import-zip"'),'Restore ZIP button missing');
assert(ui.includes("native('exportPadKitToDrive',sampleBank,JSON.stringify(settings))"),'Export must carry selected kit and music configuration');
for(const f of ['grid','drumChannel','droneChannel','bpm','rolandKit'])assert(ui.includes(f),'Kit configuration missing '+f);
assert(ui.includes("if(type==='padKitRestored')"),'Restoring kit should update UI');
assert(ui.includes("if(type==='padDriveExported')"),'Saving should report successful completion');
assert(java.includes('@JavascriptInterface public void exportPadKitToDrive(int bank,String settings)'),'Native export bridge missing');
assert(java.includes('Intent.ACTION_CREATE_DOCUMENT')&&java.includes('application/zip'),'Android picker must allow Google Drive without OAuth');
assert(java.includes('startActivityForResult(save,10)'),'Export request code must be distinct');
assert(java.includes('if(req==10)')&&java.includes('padSamples.exportZipKit('),'Selected document must receive real ZIP content');
assert(java.includes('padSamples.readZipManifest(')&&java.includes('padSamples.restoreZipLabels('),'Restore labels and layout from backup');
assert(eng.includes('new java.util.zip.ZipOutputStream('),'Backup ZIP needs actual compressed media');
assert(eng.includes('new java.util.zip.ZipEntry("graue-kit.json")'),'Kit metadata manifest missing');
assert(eng.includes('getContentResolver().openOutputStream(destination,"w")'),'Must stream actual file to DocumentsProvider');
assert(eng.includes('sourceBank')&&eng.includes('pads')&&eng.includes('file'),'Export needs pads and source metadata');
assert(eng.includes('maxTotal=70*1024*1024'),'Import keeps decompression safety bound');
assert(eng.includes('positions.get(i)'),'Sparse pad mapping must remain stable after import');
assert(css.includes('#gx-pad-export-drive'),'Drive action should be visible');
console.log('DrumPad Drive: full ZIP, audio, configuration, import, SAF/Drive export and sparse slots verified');
