'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),assert=require('node:assert/strict');
const root=path.join(__dirname,'../app/src/main/assets');
const source=fs.readFileSync(path.join(root,'tones.js'),'utf8');
const ux=fs.readFileSync(path.join(root,'ux-v2.js'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const style=fs.readFileSync(path.join(root,'ux-v2.css'),'utf8');
const nodes=new Map();
function el(id){if(!nodes.has(id))nodes.set(id,{id,value:'',textContent:'',append(){},replaceChildren(){},classList:{toggle(){},add(){},remove(){}}});return nodes.get(id);}
