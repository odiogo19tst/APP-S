const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../app/src/main');
const ui=fs.readFileSync(path.join(root,'assets/ux-v2.js'),'utf8');
const native=fs.readFileSync(path.join(root,'java/br/com/doapps/grauelive/MainActivity.java'),'utf8');
const css=fs.readFileSync(path.join(root,'assets/ux-v2.css'),'utf8');
for(const id of ['gx-cc-grid','gx-cc-status','gx-perf-local-save','gx-perf-recent','gx-perf-source'])assert(ui.includes('id="'+id+'"'),'Missing functional stage widget: '+id);
for(const cc of [7,11,10,74,71,73,72,91,93])assert(ui.includes('['+cc+',\''),'Missing live physical CC '+cc);
assert(ui.includes('function receivePhysicalCc(packet)')&&ui.includes('liveCcValues.set(channel'), 'Actual physical CC events must update controls');
assert(ui.includes('window.Native?.cc?.(ch,cc,v)'),'Mobile fader must send MIDI CC, not simply update appearance');
assert(ui.includes('if(!usbConnected)'),'Sending is gated by actual USB state');
assert(ui.includes("kind==='cachedPerformance'"),'Partial MIDI performance cache is not surfaced');
assert(ui.includes('saved.performanceHistory'),'Locally kept Performance references must persist');
assert(ui.includes('Nenhum WRITE enviado')||ui.includes('Nada escrito na memória Roland.'),'Do not write unsafe user memory');
assert(native.includes('xpsPerformanceCache')&&native.includes('emitCachedPerformance()'),'Native partial read caching missing');
assert(native.includes('gemmaLastError'),'Gemma validation diagnostics missing');
assert(native.includes('LlmInference.Backend.CPU'),'CPU retry missing for local model');
assert(native.includes('armed=ready;'),'Auto MIDI enable on connection expected');
assert(css.includes('.gx-cc-grid')&&css.includes('.gx-perf-chip'),'Compact MIDI stage layout missing');
console.log('Grauê 1.7: physical CC mirroring, Performance partial cache, Gemma diagnostics and auto-MIDI checks passed');
