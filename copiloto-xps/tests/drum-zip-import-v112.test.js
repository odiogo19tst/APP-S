const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const app=path.resolve(__dirname,'../app/src/main');
const backend=fs.readFileSync(path.join(app,'java/br/com/doapps/grauelive/PadSampleEngine.java'),'utf8');
const native=fs.readFileSync(path.join(app,'java/br/com/doapps/grauelive/MainActivity.java'),'utf8');
const ui=fs.readFileSync(path.join(app,'assets/drumpads.js'),'utf8');
const html=fs.readFileSync(path.join(app,'assets/index.html'),'utf8');
assert(backend.includes('importZipKit(int bank,Uri uri)'),'ZIP importer must exist');
assert(backend.includes('ZipInputStream'),'Only valid ZIP entries must be read');
assert(backend.includes('staged.size()>=PADS'),'Max 8 audio files');
assert(backend.includes('maxPerFile=12*1024*1024'),'12 MB per sample limit');
assert(backend.includes('maxTotal=70*1024*1024'),'70 MB extraction cap');
assert(backend.includes('File.createTempFile("graue_zip_"'),'Entries must use safe private temporary files');
assert(backend.includes('normal.contains("..")'),'Disallow traversing archive entry paths');
assert(backend.includes('java.nio.file.Files.copy'),'Files copied after extraction, not from zip paths');
assert(backend.includes('finally{for(File file:staged)file.delete();}'),'All staging files cleaned');
for(const s of ['wav','mp3','ogg'])assert(backend.includes('endsWith(".'+s+'")'),'Missing '+s+' format');
assert(native.includes('@JavascriptInterface public void importPadZip(int bank)'),'Native picker action missing');
assert(native.includes('startActivityForResult(pick,9)'),'ZIP SAF file-picker request missing');
assert(native.includes('if(req==9)')&&native.includes('padSamples.importZipKit(bank,data.getData())'),'Activity result not wired');
assert(ui.includes('id="gx-pad-import-zip"'),'UI import button missing');
assert(ui.includes("native('importPadZip',sampleBank)"),'ZIP importer not connected to native');
assert(ui.includes("el('gx-pad-import-zip').hidden=!sample"),'ZIP available only in phone audio mode');
assert(html.includes('drumpads.js'),'Drum library code must load in Android');
console.log('Grauê 1.12: ZIP sample library, SAF, size bounds and protected local extraction smoke tests passed');