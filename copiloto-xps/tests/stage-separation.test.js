// Regressão: um único serviço USB-MIDI e apresentação isolada da edição.
'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const root=path.join(__dirname,'../app/src/main/assets');
const ux=fs.readFileSync(path.join(root,'ux-v2.js'),'utf8');
const css=fs.readFileSync(path.join(root,'ux-v2.css'),'utf8');
const legacy=fs.readFileSync(path.join(root,'live.js'),'utf8');
const app=fs.readFileSync(path.join(root,'app.js'),'utf8');
const native=fs.readFileSync(path.join(__dirname,'../app/src/main/java/br/com/doapps/grauelive/MainActivity.java'),'utf8');
assert.equal((ux.match(/id="gx-show-mode"/g)||[]).length,1,'Um único controle para entrar/sair do Ao Vivo');
assert.match(ux,/id="gx-live-song-select"/,'Troca de música durante o palco');
assert.match(ux,/id="gx-live-score-toggle"/,'Cifra acessível no próprio palco');
assert.match(ux,/gx-stage-prep-only/,'Separar preparação');
assert.match(ux,/const setLiveMode=enabled=>/,'Ativar apresentação sem abrir outro editor');
assert.match(ux,/if\(liveMode&&name!=='stage'\)/,'Bloquear navegação acidental durante o show');
assert.doesNotMatch(ux,/gx-show-mode'\)\.onclick=\(\)=>callOld\('liveFocus'\)/,'Modo ao vivo não pode abrir o modo antigo');
assert.match(css,/#gx-shell\.gx-live-mode \.gx-nav/,'Menus não aparecem durante o show');
assert.match(css,/#gx-shell\.gx-live-mode \.gx-stage-prep-only/,'Editor de partes oculto durante o show');
assert.match(legacy,/f\('liveArm'\)\.hidden=true/,'O legado não deve pedir rearmar MIDI');
assert.match(app,/\$\('arm'\)\.disabled=true/,'Checkbox antigo desativado');
assert.match(native,/armed=true;emit\("armed",true\);emit\("xpsConnection",true\)/,'Portas USB habilitam envio e recepção juntos');
assert.match(native,/xps\.initialSync\(\)/,'Leitura inicial automática');
assert.match(native,/@JavascriptInterface public void selectTone\(/,'Troca de timbres preservada');
assert.match(native,/@JavascriptInterface public void selectPerformance\(/,'Troca de Performances preservada');
assert.match(native,/@JavascriptInterface public void readUserTones\(/,'Importação USER preservada');
assert.match(native,/@JavascriptInterface public void padHit\(/,'Drum pads preservados');
assert.match(native,/@JavascriptInterface public void playAssistChord\(/,'Acordes assistidos preservados');
console.log('Modo ao Vivo isolado; MIDI único; ferramentas de preparação preservadas.');
