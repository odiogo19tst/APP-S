'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const assets=path.join(__dirname,'../app/src/main/assets');
const ui=fs.readFileSync(path.join(assets,'ux-v2.js'),'utf8');
const app=fs.readFileSync(path.join(assets,'app.js'),'utf8');
const gradle=fs.readFileSync(path.join(__dirname,'../app/build.gradle'),'utf8');
assert(ui.includes('id="gx-scroll-speed-value"'),'Visible speed indicator required');
assert(ui.includes('value="3" aria-label="Velocidade da rolagem'),'Slow default expected');
assert(app.includes('scoreScrollSpeed:saved.scoreScrollSpeed||3'),'Slider preference must survive app relaunch');
assert(ui.includes('scoreSpeed.onchange=()=>{saved.scoreScrollSpeed=scrollSpeedLevel(scoreSpeed.value);persist();}'),'Slider changes must be saved');
assert(ui.includes('Math.min(100,now-lastScrollFrame)'),'Elapsed frame must be capped for background/foreground transitions');
assert(ui.includes("scoreScrolling=!scoreScrolling"),'Pause/resume control must be preserved');
const match=ui.match(/const scoreScrollRates=(\[[^;]+\]);/);
assert(match,'Rate table not found');
const rates=vm.runInNewContext(match[1]);
assert.equal(rates.length,11);
assert.equal(rates[3],3,'Default should be around 3 px/s');
assert(rates[1]<=2,'Minimum needs to be very slow');
assert(rates[10]<=25,'Maximum must not match old excessive speeds');
for(let i=2;i<=10;i++)assert(rates[i]>rates[i-1],'Speed must increase monotonically');
assert(gradle.includes('versionCode 39'),'New APK must install as upgrade');
console.log('Grauê 1.24: slow score scroll, adjustable/persistent speeds, safe pause and frame timing passed');
