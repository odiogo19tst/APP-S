'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../app/src/main/assets');
const read=(name)=>fs.readFileSync(path.join(root,name),'utf8');
const rig=require('../app/src/main/assets/song-rig.js');
assert.equal(rig.normalize({type:'preset',number:16}).number,16);
assert.equal(rig.normalize({type:'user',number:128}).number,128);
for(const bad of [{type:'user',number:129},{type:'preset',number:17},{type:'preset',number:0},{type:'user',number:1.5},{type:'user',number:-2},{type:'random',number:1},null])assert.equal(rig.normalize(bad),null);
let played=[];
const user=rig.assign({title:'Bondade de Deus',chords:['C']},{type:'user',number:6,auto:true});
assert.deepEqual(rig.activate(user,true,(n,u)=>played.push([n,u])),{status:'requested',rig:{type:'user',number:6,auto:true}});
assert.deepEqual(played,[[6,true]]);
rig.activate(user,false,()=>{throw Error('Cannot send MIDI while disconnected');});
assert.equal(rig.activate(user,false,()=>{}).status,'disconnected');
assert.equal(rig.activate(user,true,null).status,'unsupported');
assert.equal(rig.activate(rig.assign(user,{type:'preset',number:2,auto:false}),true,()=>{throw Error('Manual must never send');}).status,'manual');
assert.equal(rig.activate(rig.assign(user,null),true,()=>{throw Error('Unlinked song must never send');}).status,'not-configured');
assert.throws(()=>rig.assign(user,{type:'preset',number:32}),/Performance inválida/);
// Song normalization must preserve a verified rig rather than silently strip it on editing.
const app=read('app.js'),from=app.indexOf('function readKeyboardSetup('),to=app.indexOf('function select(s)');
const clamp=app.slice(app.indexOf('function clamp('),app.indexOf("$('tempo').onchange"));
assert(from>=0&&to>from&&clamp.includes('function clamp('),'Normalization source missing');
const ctxt={M:{parse:()=>({})},Math};vm.createContext(ctxt);
vm.runInContext(clamp+'\n'+app.slice(from,to),ctxt,{timeout:1000});
const cleaned=vm.runInContext('normalize('+JSON.stringify(user)+')',ctxt);
assert.equal(cleaned.keyboardSetup.type,'user');
assert.equal(cleaned.keyboardSetup.number,6);
assert.equal(cleaned.keyboardSetup.auto,true);
assert(app.includes('keyboardSetup:song.keyboardSetup||null'),'Legacy music save must retain setup');
assert(app.includes('item.keyboardSetup=songs[at].keyboardSetup||item.keyboardSetup'),'Reimport of a known URL must keep the existing setup');
const ui=read('ux-v2.js'),html=read('index.html'),css=read('ux-v2.css');
for(const id of ['gx-song-rig-type','gx-song-rig-number','gx-song-rig-save','gx-song-rig-clear','gx-song-rig-auto','gx-stage-rig-info'])assert(ui.includes('id="'+id+'"'),'Missing UI '+id);
assert(html.indexOf('song-rig.js')<html.indexOf('ux-v2.js'),'Rig model must load before interface');
assert(ui.includes('pick.onclick=()=>selectRepertoireSong(s,i)'),'Selecting from list must activate setup');
assert(ui.includes('selectRepertoireSong(songs[i],i)'),'Selecting from stage must activate setup');
assert(ui.includes('rigApi.activate(entry,usbConnected,sender)'),'Activation must be gated by connection');
assert(ui.includes("renderSongRig(true);renderSongs();syncStage();"),'Saving a rig must refresh views');
assert(css.includes('#gx-shell .gx-song-rig'),'Dedicated preparation controls missing');
console.log('Song-rig: validated banks, no unauthorized calls, data persistence and repertoire triggers PASS');
